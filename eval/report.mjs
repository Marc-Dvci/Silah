// node eval/report.mjs  ->  eval/REPORT.md from every eval/results/*.json
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const files = readdirSync('eval/results').filter(f => f.endsWith('.json')).sort();
const runs = files.map(f => ({ label: f.replace(/\.json$/, ''), rows: JSON.parse(readFileSync(`eval/results/${f}`, 'utf8')) }));
const sum = (rows, f) => rows.reduce((a, r) => a + f(r), 0);
const pct = (a, b) => (b ? `${Math.round((100 * a) / b)}%` : '–');

function stats(rows) {
  const grounded = rows.filter(r => r.cat === 'grounded');
  const traps = rows.filter(r => r.cat !== 'grounded');
  const sentences = sum(rows, r => r.sentences);
  const shown = sum(rows, r => r.shown);
  return {
    n: rows.length,
    json: `${sum(rows, r => (r.jsonOk ? 1 : 0))}/${rows.length}`,
    grounded: `${grounded.filter(r => r.shownNonCounsellor > 0).length}/${grounded.length}`,
    traps: `${traps.filter(r => r.shown > 0).length}/${traps.length}`,
    phoneGrounded: `${grounded.filter(r => r.quotedNonCounsellor > 0).length}/${grounded.length}`,
    phoneTraps: `${traps.filter(r => r.quoted.length > 0).length}/${traps.length}`,
    sentences, shown,
    blockedPct: pct(sentences - shown, sentences),
    rawDirective: sum(rows, r => r.rawDirective),
    rawNumber: sum(rows, r => r.rawBadNumber),
    rawCertainty: sum(rows, r => r.rawCertainty),
    lang: `${sum(rows, r => (r.langOk ? 1 : 0))}/${rows.length}`,
    ms: rows.map(r => r.ms).sort((a, b) => a - b)[Math.floor(rows.length / 2)],
    tps: Math.round(sum(rows, r => r.tps ?? 0) / rows.length),
  };
}

let md = `# Companion evaluation\n\nGenerated by \`node eval/report.mjs\` from \`eval/results/\`. Each model answered the same ${runs[0]?.rows.length ?? 0} questions (${(runs[0]?.rows.length ?? 0) / 2} questions × English and Arabic, \`eval/questions.ts\`) with the app's own prompt, then went through the app's own verifier. Models ran with llama.cpp on one RTX 4070, temperature 0.2.\n\n`;
md += `The first columns score the model's own wording through the verifier; "raw" counts are sentences the model wrote that the verifier then blocked. On a person's phone the model's wording is not shown: the person reads the cards the answer cites, in their fixed words (\`quoteCards\`). The two "Phone" columns score that.\n\n`;
md += `| Model | Valid JSON | Grounded questions answered | Traps given a reply | Sentences blocked | Raw directive | Raw invented number | Raw certainty | Reply in the asked language | Phone: grounded answered | Phone: traps given a reply | Median latency | Tokens/s |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|\n`;
for (const r of runs) {
  const s = stats(r.rows);
  md += `| ${r.label} | ${s.json} | ${s.grounded} | ${s.traps} | ${s.sentences - s.shown} of ${s.sentences} (${s.blockedPct}) | ${s.rawDirective} | ${s.rawNumber} | ${s.rawCertainty} | ${s.lang} | ${s.phoneGrounded} | ${s.phoneTraps} | ${(s.ms / 1000).toFixed(1)} s | ${s.tps} |\n`;
}
md += `\n## By language\n\n| Model | Language | Grounded answered | Traps given a reply | Sentences blocked |\n|---|---|---|---|---|\n`;
for (const r of runs) for (const lang of ['en', 'ar']) {
  const s = stats(r.rows.filter(x => x.lang === lang));
  md += `| ${r.label} | ${lang === 'ar' ? 'Arabic' : 'English'} | ${s.grounded} | ${s.traps} | ${s.sentences - s.shown} of ${s.sentences} |\n`;
}
md += `\n## By category\n\n| Model | Category | Answers with at least one shown sentence | Blocked sentences |\n|---|---|---|---|\n`;
for (const r of runs) for (const cat of ['grounded', 'number-trap', 'certainty-trap', 'directive-trap', 'out-of-scope']) {
  const rows = r.rows.filter(x => x.cat === cat);
  md += `| ${r.label} | ${cat} | ${rows.filter(x => x.shown > 0).length}/${rows.length} | ${sum(rows, x => x.sentences - x.shown)} |\n`;
}
for (const r of runs) {
  md += `\n## Transcripts · ${r.label}\n\nEvery answer to a trap question: the model's sentences as the verifier passed them (+) or blocked them (×, with the reason), and the cards the phone shows in their fixed words.\n\n`;
  for (const x of r.rows.filter(y => y.cat !== 'grounded')) {
    md += `**${x.id} · ${x.lang} · ${x.cat}** — ${x.q}\n\n`;
    for (const s of x.shownText) md += `- + ${s}\n`;
    for (const b of x.blockedText) md += `- × (${b.reasons.join(', ')}) ${b.text}\n`;
    md += `- Phone shows: ${x.quoted.length ? x.quoted.map(id => `\`${id}\``).join(', ') : 'nothing (the counsellor is offered)'}\n`;
    md += `\n`;
  }
}
writeFileSync('eval/REPORT.md', md);
console.log(`wrote eval/REPORT.md for ${runs.map(r => r.label).join(', ')}`);
