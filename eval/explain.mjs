// node eval/explain.mjs <label> "<model name>" [base]  ->  eval/results/explain/<label>.json, eval/EXPLAIN.md,
// and (for the label given with --publish) src/llm/precomputed.json: the explanations the demo shows for its
// fictional people, re-checked by the verifier on the phone when they are shown.
import { createServer } from 'vite';
import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';

const args = process.argv.slice(2);
const publish = args.includes('--publish');
const [label, model, base = 'http://127.0.0.1:8080'] = args.filter(a => a !== '--publish');
const server = await createServer({ configFile: false, cacheDir: 'node_modules/.vite-scripts', server: { middlewareMode: true }, appType: 'custom', logLevel: 'silent' });
const mod = await server.ssrLoadModule('/eval/explain.ts');
mkdirSync('eval/results/explain', { recursive: true });
if (label && model) {
  const rows = await mod.run(base, model);
  writeFileSync(`eval/results/explain/${label}.json`, JSON.stringify(rows, null, 1));
}

// Report over every saved run, re-scored with the current verifier and the current cards.
const { verifyExplanation } = await server.ssrLoadModule('/src/llm/explain.ts');
const cases = new Map(mod.cases().map(c => [c.key, c]));
const files = readdirSync('eval/results/explain').filter(f => f.endsWith('.json')).sort();
let md = '# Plain-language explanations: model writes, verifier decides\n\n';
md += 'Generated by `node eval/explain.mjs` from the saved runs in `eval/results/explain/`, re-scored with the current verifier and cards. ';
md += 'Each run asks the model for an explanation of every demo persona and every sample report: for the person in English and in Arabic, and a paragraph for the clinician in English. ';
md += 'A sentence is shown only if the verifier passes it (cites a card, uses only that card\'s numbers, binds each chance to its outcome and person, does not steer, states no certainty about a child). ';
md += 'An explanation is shown only if at least two of its sentences pass; otherwise the phone keeps the fixed checked text only.\n\n';
md += '| Model | Explanations | Unreadable output | Sentences | Passed | Held back | Explanations shown | Held back by reason |\n|---|---|---|---|---|---|---|---|\n';
const all = {};
for (const f of files) {
  const rows = JSON.parse(readFileSync(`eval/results/explain/${f}`, 'utf8'));
  let sent = 0, ok = 0, shownN = 0, errors = 0;
  const reasons = {};
  for (const r of rows) {
    if (!r.e) { errors++; continue; }
    const c = cases.get(r.case);
    const v = c ? verifyExplanation(r.e.sentences, c.cards) : r.e.sentences;
    r.e.sentences = v;
    sent += v.length;
    const pass = v.filter(s => s.ok).length;
    ok += pass;
    if (pass >= 2) shownN++;
    for (const s of v) for (const x of s.reasons ?? []) reasons[x] = (reasons[x] ?? 0) + 1;
  }
  all[f] = rows;
  const rs = Object.entries(reasons).map(([k, n]) => `${k} ${n}`).join(', ') || 'none';
  md += `| ${f.replace(/\.json$/, '')} | ${rows.length} | ${errors} | ${sent} | ${ok} | ${sent - ok} | ${shownN}/${rows.length} | ${rs} |\n`;
}
md += '\nReasons: `number` a number not on the cited cards; `binding` a chance attached to the wrong outcome or person, or a carrier called ill; `directive` steers a decision; `certainty` states an outcome for a particular child; `no-card` / `unknown-card` cites nothing or a card that does not exist.\n\n';
md += '## Sentences held back\n\nEvery sentence the verifier held back, with its reasons, so the gate can be audited.\n\n';
for (const [f, rows] of Object.entries(all)) {
  md += `### ${f.replace(/\.json$/, '')}\n\n`;
  for (const r of rows) for (const s of r.e?.sentences ?? []) if (!s.ok) md += `- ${r.label}, ${r.audience}, ${r.lang}: “${s.text}” (${(s.reasons ?? []).join(', ')}; cites ${s.cards.join(', ') || 'nothing'})\n`;
  md += '\n';
}
writeFileSync('eval/EXPLAIN.md', md);

if (publish && label) {
  const rows = all[`${label}.json`];
  const pre = existsSync('src/llm/precomputed.json') ? JSON.parse(readFileSync('src/llm/precomputed.json', 'utf8')) : {};
  for (const r of rows) {
    if (!r.e) continue;
    pre[`${r.case}:${r.audience}:${r.lang}`] = { model: r.e.model, at: r.e.at, sentences: r.e.sentences.map(s => ({ text: s.text, cards: s.cards })) };
  }
  writeFileSync('src/llm/precomputed.json', JSON.stringify(pre, null, 1) + '\n');
  console.log(`published ${rows.length} explanations to src/llm/precomputed.json`);
}
await server.close();
console.log(md.split('\n').slice(0, 12).join('\n'));
// The app's demo network keeps a BroadcastChannel open; end the process explicitly.
process.exit(0);
