// node eval/binding.mjs  ->  eval/BINDING.md: the claim-binding mutation test over eval/results/*.json
import { createServer } from 'vite';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const server = await createServer({ configFile: false, cacheDir: 'node_modules/.vite-scripts', server: { middlewareMode: true }, appType: 'custom', logLevel: 'silent' });
const { mutate } = await server.ssrLoadModule('/eval/binding.ts');
const files = readdirSync('eval/results').filter(f => f.endsWith('.json')).sort();
const runs = files.map(f => {
  const label = f.replace(/\.json$/, '');
  const cards = JSON.parse(readFileSync(`eval/results/cards/${f}`, 'utf8')).cards;
  return { label, ...mutate(label, JSON.parse(readFileSync(`eval/results/${f}`, 'utf8')), cards) };
});
await server.close();

const all = runs.flatMap(r => r.mutants);
const live = all.filter(m => m.numberCheckPasses);
let md = `# Claim binding: mutation test\n\nGenerated by \`node eval/binding.mjs\` from the saved model answers in \`eval/results/\` (no model is called).\n\n`;
md += `Every sentence the verifier showed that states a chance for a named outcome (affected, carrier, neither, not affected, birth defect from any cause) is copied, and that chance is replaced by another value from the same cited cards. The new number is on the card, so a check of numbers alone passes it; only the binding check can see that it now belongs to the wrong outcome or the wrong person.\n\n`;
md += `| Model | Sentences shown | With a chance tied to an outcome | Chances | Mutants | Mutants the number check alone passes | Of those, blocked by binding |\n|---|---|---|---|---|---|---|\n`;
for (const r of runs) {
  const l = r.mutants.filter(m => m.numberCheckPasses);
  md += `| ${r.label} | ${r.sentences} | ${r.withClaims} | ${r.claims} | ${r.mutants.length} | ${l.length} | ${l.filter(m => m.blocked).length} |\n`;
}
md += `| **All** | ${runs.reduce((a, r) => a + r.sentences, 0)} | ${runs.reduce((a, r) => a + r.withClaims, 0)} | ${runs.reduce((a, r) => a + r.claims, 0)} | ${all.length} | ${live.length} | ${live.filter(m => m.blocked).length} |\n\n`;
md += `The original sentences are the control: re-scored with the binding check, none of them is blocked (\`node eval/run.mjs <model> --rescore\`).\n\n`;
const missed = live.filter(m => !m.blocked);
md += `## Mutants not blocked (${missed.length})\n\n`;
for (const m of missed) md += `- ${m.model} · ${m.id} · ${m.lang}: ${m.claim} → ${m.to}\n  - ${m.mutant}\n`;
md += `\n## Examples blocked\n\n`;
for (const m of live.filter(x => x.blocked).slice(0, 12)) md += `- ${m.lang} · ${m.claim} → ${m.to}: ${m.mutant}\n`;
writeFileSync('eval/BINDING.md', md);
console.log(JSON.stringify({ mutants: all.length, numberCheckPasses: live.length, blocked: live.filter(m => m.blocked).length, missed: missed.length }));
