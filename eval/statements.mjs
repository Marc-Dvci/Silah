// node eval/statements.mjs  ->  docs/review/STATEMENTS.md and docs/review/statements_review.csv
import { createServer } from 'vite';
import { mkdirSync, writeFileSync } from 'node:fs';

const server = await createServer({ configFile: false, cacheDir: 'node_modules/.vite-scripts', server: { middlewareMode: true }, appType: 'custom', logLevel: 'silent' });
const { statements } = await server.ssrLoadModule('/eval/statements.ts');
const rows = statements();
await server.close();

mkdirSync('docs/review', { recursive: true });
let md = `# Every statement Silah can show, for clinical review\n\nGenerated by \`node eval/statements.mjs\` from the app's own code (${rows.length} statements). Review instructions: \`docs/review/REVIEW_PROTOCOL.md\`. The same rows, with columns for the reviewer's verdict, are in \`statements_review.csv\`.\n\n`;
let group = '';
for (const r of rows) {
  if (r.group !== group) { group = r.group; md += `\n## ${group}\n\n`; }
  md += `**${r.id}**\n\n- EN: ${r.en}\n- AR: ${r.ar}\n`;
  if (r.sources) md += `- Sources: ${r.sources}\n`;
  if (r.arithmetic) md += `- Arithmetic: ${r.arithmetic}\n`;
  md += `\n`;
}
writeFileSync('docs/review/STATEMENTS.md', md);
const q = s => `"${String(s).replace(/"/g, '""')}"`;
const csv = ['group,id,english,arabic,sources,arithmetic,correct (yes/no),non-directive (yes/no),suggested wording,comment']
  .concat(rows.map(r => [r.group, r.id, r.en, r.ar, r.sources, r.arithmetic, '', '', '', ''].map(q).join(',')));
writeFileSync('docs/review/statements_review.csv', '﻿' + csv.join('\r\n'));
console.log(`wrote ${rows.length} statements`);
